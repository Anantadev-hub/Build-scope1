import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(e.stack || e.message));
await p.goto('http://127.0.0.1:3000/register', { waitUntil: 'networkidle' });
await p.getByLabel('Full name').fill('Debug One');
await p.getByLabel('Email address').fill('dbg1@example.com');
await p.getByRole('textbox', { name: 'Password', exact: true }).fill('passw0rd1');
await p.getByRole('textbox', { name: 'Confirm password', exact: true }).fill('passw0rd1');
await p.getByText(/I understand this is a local demo workspace/i).click();
await p.getByRole('button', { name: /Create demo account/i }).click();
await p.waitForURL(/welcome/);
await p.getByRole('button', { name: /Start a new investigation/i }).click();
await p.waitForURL(/projects\/new/);
await p.waitForTimeout(400);
console.log('FORM VISIBLE:', await p.getByLabel(/Project name/i).count());
await p.getByLabel(/Project name/i).fill('Debug case');
await p.getByRole('button', { name: /Open case file/i }).click();
await p.waitForTimeout(1000);
console.log('URL:', p.url());
const st = await p.evaluate(() => {
  const s = JSON.parse(localStorage.getItem('buildscope.ai.session.v1') || 'null');
  const k = s ? `buildscope.ai.workspace.v2:${s.accountId}` : null;
  const d = k ? JSON.parse(localStorage.getItem(k) || '{}') : {};
  return { projects: (d.projects || []).map(x => x.name), welcomed: d.preferences?.welcomed };
});
console.log('STATE:', JSON.stringify(st));
console.log('ERRORS:\n' + errs.slice(0, 2).join('\n=====\n'));
await b.close();
